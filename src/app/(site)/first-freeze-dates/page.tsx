const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
const MONTHS_LONG = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]

function parts(iso: string) {
  const [y, m, d] = iso.split("-").map(Number)
  return { y, m, d }
}
function short(iso: string) {
  const { m, d } = parts(iso)
  return `${MONTHS[m - 1]} ${d}`
}
function long(iso: string) {
  const { y, m, d } = parts(iso)
  return `${MONTHS_LONG[m - 1]} ${d}, ${y}`
}
/** Day of year on a fixed non-leap calendar, so dates compare across years. */
function doy(iso: string) {
  const { m, d } = parts(iso)
  const cum = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]
  return cum[m - 1] + d
}
function fromDoy(n: number) {
  const cum = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334, 365]
  let m = 0
  while (m < 11 && n > cum[m + 1]) m++
  return `${MONTHS[m]} ${n - cum[m]}`
}
function isComplete(y: { year: number; through: string }) {
  return y.through >= `${y.year}-12-01`
}
function median(nums: number[]) {
  const s = [...nums].sort((a, b) => a - b)
  const mid = Math.floor(s.length / 2)
  return s.length % 2 ? s[mid] : Math.round((s[mid - 1] + s[mid]) / 2)
}

// Summary figures, all computed from the data file
const CURRENT_YEAR = Math.max(...FREEZE_STATIONS.flatMap((s) => s.years.map((y) => y.year)))
const completeYears = (s: FreezeStation) => s.years.filter((y) => isComplete(y) && y.hardFreeze)
const medians = FREEZE_STATIONS.map((s) => ({ name: s.name, doy: median(completeYears(s).map((y) => doy(y.hardFreeze!))) }))
const medianLow = fromDoy(Math.min(...medians.map((m) => m.doy)))
const medianHigh = fromDoy(Math.max(...medians.map((m) => m.doy)))
const allHard = FREEZE_STATIONS.flatMap((s) => completeYears(s).map((y) => ({ station: s.name, year: y.year, iso: y.hardFreeze!, doy: doy(y.hardFreeze!) })))
const earliestDoy = Math.min(...allHard.map((h) => h.doy))
const latestDoy = Math.max(...allHard.map((h) => h.doy))
const earliestYears = [...new Set(allHard.filter((h) => h.doy === earliestDoy).map((h) => h.year))].sort()
const latest = allHard.find((h) => h.doy === latestDoy)!
const novemberShare = Math.round((100 * allHard.filter((h) => parts(h.iso).m >= 11).length) / allHard.length)
const thisYear = FREEZE_STATIONS.map((s) => s.years.find((y) => y.year === CURRENT_YEAR)).filter(Boolean)
const thisYearFrost = thisYear.map((y) => y!.firstFrost).filter(Boolean).sort()[0] ?? null
const thisYearHard = thisYear.map((y) => y!.hardFreeze).filter(Boolean).sort()[0] ?? null
const thisYearThrough = thisYear.map((y) => y!.through).sort().at(-1)!
const YEARS = Array.from(new Set(FREEZE_STATIONS.flatMap((s) => s.years.map((y) => y.year)))).sort((a, b) => b - a)

