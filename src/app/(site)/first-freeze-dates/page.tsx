function Cell({ y }: { y?: { firstFrost: string | null; hardFreeze: string | null; through: string; year: number } }) {
  if (!y) return <td className="px-4 py-3 text-sm text-muted-foreground">No record</td>
  const partial = !isComplete(y)
  if (!y.hardFreeze) {
    return (
      <td className="px-4 py-3 align-top">
        <span className="block text-sm font-semibold text-foreground">{partial ? `None through ${short(y.through)}` : "None recorded"}</span>
        {y.firstFrost && <span className="block text-xs text-muted-foreground mt-0.5">Frost {short(y.firstFrost)}</span>}
      </td>
    )
  }
  const november = parts(y.hardFreeze).m >= 11
  return (
    <td className="px-4 py-3 align-top">
      <span className={cn("block text-sm font-semibold", november ? "text-primary" : "text-foreground")}>{short(y.hardFreeze)}</span>
      {y.firstFrost && <span className="block text-xs text-muted-foreground mt-0.5">Frost {short(y.firstFrost)}</span>}
    </td>
  )
}

