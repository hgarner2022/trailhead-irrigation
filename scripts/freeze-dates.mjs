#!/usr/bin/env node
// Pulls NOAA GHCN-Daily records for the stations nearest Trailhead's six
// towns and writes src/lib/freeze-data.ts: the first fall night at or below
// 32°F (first frost) and at or below 28°F (hard freeze) for each year.
// Run once a year after the first hard freeze: npm run freeze-dates
// Source: https://www.ncei.noaa.gov/pub/data/ghcn/daily/by_station/<ID>.csv.gz
// TMIN is stored in tenths of a degree Celsius. 32°F = 0; 28°F = -2.2°C = -22.
import { gunzipSync } from "node:zlib"
import { writeFileSync } from "node:fs"

const STATIONS = [
  { id: "USC00055116", name: "Longmont 2 ESE", towns: ["Longmont"], firstYear: 2018 },
  { id: "USC00050848", name: "Boulder", towns: ["Louisville", "Lafayette"], firstYear: 2015 },
  { id: "USC00055984", name: "Northglenn", towns: ["Broomfield"], firstYear: 2015 },
  { id: "USC00050950", name: "Brighton 3 SE", towns: ["Firestone"], firstYear: 2015 },
]
const LAST_YEAR = new Date().getFullYear()

async function fetchStation(id) {
  const res = await fetch(`https://www.ncei.noaa.gov/pub/data/ghcn/daily/by_station/${id}.csv.gz`)
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`)
  const buf = Buffer.from(await res.arrayBuffer())
  return gunzipSync(buf).toString("utf8")
}

function firstFreezes(csv, year) {
  let first32 = null, first28 = null, lastDay = null
  for (const line of csv.split("\n")) {
    const cols = line.split(",")
    if (cols[2] !== "TMIN") continue
    const d = cols[1]
    if (d.slice(0, 4) !== String(year) || d.slice(4) < "0801") continue
    const t = parseInt(cols[3], 10)
    if (Number.isNaN(t)) continue
    if (!lastDay || d > lastDay) lastDay = d
    if (first32 === null && t <= 0) first32 = d
    if (first28 === null && t <= -22) first28 = d
  }
  return { first32, first28, lastDay }
}

const iso = (d) => (d ? `${d.slice(0, 4)}-${d.slice(4, 6)}-${d.slice(6, 8)}` : null)

const out = []
for (const s of STATIONS) {
  const csv = await fetchStation(s.id)
  const years = []
  for (let y = s.firstYear; y <= LAST_YEAR; y++) {
    const r = firstFreezes(csv, y)
    if (!r.lastDay) continue
    years.push({ year: y, firstFrost: iso(r.first32), hardFreeze: iso(r.first28), through: iso(r.lastDay) })
  }
  out.push({ ...s, years })
  console.log(`${s.name}: ${years.length} years`)
}

const ts = `// GENERATED by scripts/freeze-dates.mjs from NOAA GHCN-Daily. Do not edit by hand.
// Generated ${new Date().toISOString().slice(0, 10)}.
// firstFrost: first fall night at or below 32°F. hardFreeze: first at or below 28°F.
// through: the last day with data that year (the current year is partial).

export type FreezeYear = { year: number; firstFrost: string | null; hardFreeze: string | null; through: string }
export type FreezeStation = { id: string; name: string; towns: string[]; firstYear: number; years: FreezeYear[] }

export const FREEZE_DATA_GENERATED = "${new Date().toISOString().slice(0, 10)}"

export const FREEZE_STATIONS: FreezeStation[] = ${JSON.stringify(out, null, 2)}
`
writeFileSync("src/lib/freeze-data.ts", ts)
console.log("wrote src/lib/freeze-data.ts")
